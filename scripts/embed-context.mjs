// Embeds the case files and prompts as TS strings so serverless functions can read them.
import fs from "node:fs";
const items = [
  ["SERVICES_MD", "context/services.md"],
  ["QUALIFIED_MD", "context/qualified.md"],
  ["PRICING_MD", "context/pricing.md"],
  ["GRADER_PROMPT_MD", "prompts/gemini_grading_prompt.md"],
];
let out = "// Generated by scripts/embed-context.mjs from /context and /prompts. Do not edit by hand.\n" +
  "// pricing.md goes to the GRADER only (to judge a volunteered budget). The voice agent never sees it.\n";
for (const [name, file] of items) out += `export const ${name} = ${JSON.stringify(fs.readFileSync(file, "utf8"))};\n`;
fs.writeFileSync("lib/grading/context.ts", out);
console.log("embedded", items.length, "files");
